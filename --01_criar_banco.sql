CREATE DATABASE UniversidadeVenturi

GO

USE UniversidadeVenturi;
GO

CREATE TABLE ALUNOS
(
    MATRICULA INT IDENTITY(1,1) NOT NULL,
    NOME VARCHAR(50) NOT NULL,

    CONSTRAINT PK_ALUNO PRIMARY KEY (MATRICULA)
);
GO

CREATE TABLE CURSOS
(
    CURSO CHAR(3) NOT NULL,
    NOME VARCHAR(50) NOT NULL,

    CONSTRAINT PK_CURSO PRIMARY KEY (CURSO)
);
GO

CREATE TABLE PROFESSOR
(
    PROFESSOR INT IDENTITY(1,1) NOT NULL,
    NOME VARCHAR(50) NOT NULL,

    CONSTRAINT PK_PROFESSOR PRIMARY KEY (PROFESSOR)
);
GO

CREATE TABLE MATERIAS
(
    SIGLA CHAR(3) NOT NULL,
    NOME VARCHAR(50) NOT NULL,
    CARGAHORARIA INT NOT NULL,
    CURSO CHAR(3) NOT NULL,
    PROFESSOR INT NOT NULL,

    CONSTRAINT PK_MATERIA PRIMARY KEY (SIGLA),

    CONSTRAINT FK_CURSO
        FOREIGN KEY (CURSO)
        REFERENCES CURSOS (CURSO),

    CONSTRAINT FK_PROFESSOR
        FOREIGN KEY (PROFESSOR)
        REFERENCES PROFESSOR (PROFESSOR)
);
GO

CREATE TABLE MATRICULA
(
    MATRICULA INT NOT NULL,
    CURSO CHAR(3) NOT NULL,
    MATERIA CHAR(3) NOT NULL,
    PROFESSOR INT NOT NULL,
    PERLETIVO INT NOT NULL,

    N1 FLOAT NULL,
    N2 FLOAT NULL,
    N3 FLOAT NULL,
    N4 FLOAT NULL,

    TOTALPONTOS FLOAT NULL,
    MEDIA FLOAT NULL,

    F1 INT NULL,
    F2 INT NULL,
    F3 INT NULL,
    F4 INT NULL,

    TOTALFALTAS INT NULL,
    PERCFREQ FLOAT NULL,
    RESULTADO VARCHAR(20) NULL,

    MEDIAFINAL FLOAT NULL,
    NOTAEXAME FLOAT NULL,

    CONSTRAINT PK_MATRICULA PRIMARY KEY
    (
        MATRICULA,
        CURSO,
        MATERIA,
        PROFESSOR,
        PERLETIVO
    ),

    CONSTRAINT FK_ALUNOS_MATRICULA
        FOREIGN KEY (MATRICULA)
        REFERENCES ALUNOS (MATRICULA),

    CONSTRAINT FK_CURSOS_MATRICULA
        FOREIGN KEY (CURSO)
        REFERENCES CURSOS (CURSO),

    CONSTRAINT FK_MATERIAS
        FOREIGN KEY (MATERIA)
        REFERENCES MATERIAS (SIGLA),

    CONSTRAINT FK_PROFESSOR_MATRICULA
        FOREIGN KEY (PROFESSOR)
        REFERENCES PROFESSOR (PROFESSOR)
);
GO


