SELECT *
FROM PROFESSOR;
GO

--Listar materias com seus cursos e professores
SELECT
    M.SIGLA,
    M.NOME AS MATERIA,
    M.CARGAHORARIA,
    C.NOME AS CURSO,
    P.NOME AS PROFESSOR
FROM MATERIAS AS M
INNER JOIN CURSOS AS C
    ON C.CURSO = M.CURSO
INNER JOIN PROFESSOR AS P
    ON P.PROFESSOR = M.PROFESSOR;
GO

-- Listar alunos matriculados e suas materias
SELECT
    A.MATRICULA,
    A.NOME AS ALUNO,
    C.NOME AS CURSO,
    M.NOME AS MATERIA,
    MA.PERLETIVO
FROM MATRICULA AS MA
INNER JOIN ALUNOS AS A
    ON A.MATRICULA = MA.MATRICULA
INNER JOIN CURSOS AS C
    ON C.CURSO = MA.CURSO
INNER JOIN MATERIAS AS M
    ON M.SIGLA = MA.MATERIA
ORDER BY A.NOME, M.NOME;
GO

-- 6. Consultar notas, faltas, media e resultado
SELECT
    A.NOME AS ALUNO,
    MA.CURSO,
    MA.MATERIA,
    MA.PERLETIVO,
    MA.N1,
    MA.N2,
    MA.N3,
    MA.N4,
    MA.MEDIA,
    MA.TOTALFALTAS,
    MA.PERCFREQ,
    MA.NOTAEXAME,
    MA.MEDIAFINAL,
    MA.RESULTADO
FROM MATRICULA AS MA
INNER JOIN ALUNOS AS A
    ON A.MATRICULA = MA.MATRICULA
ORDER BY A.NOME, MA.PERLETIVO;
GO

--Listar somente alunos aprovados
SELECT
    A.NOME AS ALUNO,
    MA.MATERIA,
    MA.PERLETIVO,
    MA.MEDIAFINAL,
    MA.RESULTADO
FROM MATRICULA AS MA
INNER JOIN ALUNOS AS A
    ON A.MATRICULA = MA.MATRICULA
WHERE MA.RESULTADO = 'APROVADO';
GO

--Listar alunos em exame
SELECT
    A.NOME AS ALUNO,
    MA.MATERIA,
    MA.PERLETIVO,
    MA.MEDIA,
    MA.RESULTADO
FROM MATRICULA AS MA
INNER JOIN ALUNOS AS A
    ON A.MATRICULA = MA.MATRICULA
WHERE MA.RESULTADO = 'EXAME';
GO

--Listar alunos reprovados
SELECT
    A.NOME AS ALUNO,
    MA.MATERIA,
    MA.PERLETIVO,
    MA.MEDIAFINAL,
    MA.PERCFREQ,
    MA.RESULTADO
FROM MATRICULA AS MA
INNER JOIN ALUNOS AS A
    ON A.MATRICULA = MA.MATRICULA
WHERE MA.RESULTADO = 'REPROVADO';
GO
